#!/usr/bin/env python3
"""
Package the built benchmark for people outside this repository.

    python export_dataset.py
    python export_dataset.py -o /tmp/bench --export-dir /tmp/bench/export
    python export_dataset.py --no-lm-eval
"""
from __future__ import annotations

import argparse
import collections
import json
from pathlib import Path
from typing import Any, Dict, List

from corpusbench.common import (BENCHMARK_NAME, BENCHMARK_VERSION, SCHEMA_VERSION,
                    add_common_args, describe, log, manifest_entry, read_jsonl,
                    resolve_config, utc_now, write_json)

LOG = log("export")

TRACKS = {
    "1": ("track1_dapt.jsonl", "dapt", "Perplexity over held-out regulation text"),
    "2": ("track2_sft.jsonl", "sft", "Verifiable facts mined from held-out regulation"),
    "3": ("track3_vlm.jsonl", "vlm", "IFC element recognition, keyed by the IFC file"),
}

# One task file per scorable track. Perplexity is left out: lm-eval computes it
LM_EVAL_TEMPLATE = """\
# {name} — {desc}
# Generated by export_dataset.py. Do not edit by hand; rebuild instead.
task: {task}
dataset_path: json
dataset_kwargs:
  data_files:
    test: {file}
test_split: test
output_type: generate_until
doc_to_text: "{doc_to_text}"
doc_to_target: "{{{{answer}}}}"
generation_kwargs:
  until: ["\\n\\n"]
  do_sample: false
  temperature: 0.0
  max_gen_toks: {max_toks}
metric_list:
  - metric: exact_match
    aggregation: mean
    higher_is_better: true
metadata:
  version: {version}
  benchmark: {benchmark}
  note: >-
    exact_match here is the harness default and is stricter than this
    benchmark's own grader, which parses numbers with tolerance and compares
    name sets as sets. Use evaluate.py for the reported score.
"""


def _counts(rows: List[dict]) -> Dict[str, Any]:
    return {
        "items": len(rows),
        "by_eval_type": dict(collections.Counter(r.get("eval_type") for r in rows)),
        "by_category": dict(collections.Counter(r.get("category") for r in rows)),
        "documents": len({r.get("doc") for r in rows}),
    }


def write_manifest(cfg, export_dir: Path) -> Path:
    """Checksums and counts for every artefact this build produced."""
    files, tracks = [], {}
    for t, (fname, _, _) in sorted(TRACKS.items()):
        path = cfg["out_dir"] / fname
        if not path.exists():
            continue
        files.append(manifest_entry(path))
        tracks[f"track{t}"] = _counts(read_jsonl(path))

    for extra in ("holdout.json", "provenance.jsonl", "contamination_report.json",
                  "rejections.json"):
        path = cfg["out_dir"] / extra
        if path.exists():
            files.append(manifest_entry(path))

    contamination = {}
    cpath = cfg["out_dir"] / "contamination_report.json"
    if cpath.exists():
        report = json.loads(cpath.read_text(encoding="utf-8"))
        contamination = {"items": report.get("items"),
                         "fully_verified": report.get("fully_verified"),
                         "failures": report.get("failures", {})}

    return write_json(export_dir / "manifest.json", {
        "benchmark": BENCHMARK_NAME,
        "version": BENCHMARK_VERSION,
        "item_schema": SCHEMA_VERSION,
        "built_at": utc_now(),
        "generated_dir": str(cfg["generated_dir"]),
        "corpus_dir": str(cfg["corpus_dir"]),
        "config": {k: v for k, v in cfg.items()
                   if k in ("holdout", "track2_sft", "track3_vlm", "eval")},
        "tracks": tracks,
        "files": files,
        "contamination": contamination,
    })


def write_lm_eval(cfg, export_dir: Path) -> List[Path]:
    out_dir = export_dir / "lm_eval"
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for t in ("2", "3"):
        fname, short, desc = TRACKS[t]
        path = cfg["out_dir"] / fname
        if not path.exists():
            continue
        doc_to_text = ("다음 조문을 읽고 질문에 답하시오.\\n\\n[조문]\\n{{context}}\\n\\n"
                       "[질문]\\n{{question_ko}}\\n\\n{{instruction_ko}}") if t == "2" else \
                      "{{question_ko}}\\n\\n{{instruction_ko}}"
        target = out_dir / f"{BENCHMARK_NAME}_{short}.yaml"
        target.write_text(LM_EVAL_TEMPLATE.format(
            name=f"{BENCHMARK_NAME}-{short}", desc=desc,
            task=f"{BENCHMARK_NAME}_{short}", file=f"../{fname}",
            doc_to_text=doc_to_text, max_toks=256 if t == "2" else 128,
            version=BENCHMARK_VERSION, benchmark=BENCHMARK_NAME), encoding="utf-8")
        written.append(target)
    return written


def write_card(cfg, export_dir: Path) -> Path:
    manifest = json.loads((export_dir / "manifest.json").read_text(encoding="utf-8"))
    tracks = manifest["tracks"]
    cont = manifest.get("contamination", {})
    hp = cfg["out_dir"] / "holdout.json"
    holdout = json.loads(hp.read_text(encoding="utf-8")) if hp.exists() else {}
    totals = holdout.get("totals", {})

    def row(track: str, label: str) -> str:
        t = tracks.get(track)
        if not t:
            return f"| {label} | not built | |"
        kinds = ", ".join(f"{k} {v}" for k, v in sorted(t["by_eval_type"].items()))
        return f"| {label} | {t['items']} | {kinds} |"

    body = f"""\
# {BENCHMARK_NAME} {BENCHMARK_VERSION} — Korean construction LLM/VLM benchmark

A held-out evaluation set for models trained on a corpus of Korean construction
regulation and BIM models. 한국 건설 법령과 BIM 모델로 학습한 모델을 평가하기 위한
홀드아웃 벤치마크입니다.

- **Item schema**: `{SCHEMA_VERSION}`
- **Built**: {manifest['built_at']}
- **Source dataset**: `{Path(manifest['generated_dir']).name}`
- **Languages**: Korean (ko) prompts, English (en) prompts on every item
- **Answer key**: source document, IFC file, arithmetic. No model wrote it.

## What it measures / 무엇을 재는가

The question it answers is *"did training help, and where?"* — a base checkpoint
against a fine-tuned one, on identical frozen items. It is not a ranking against
other people's models: the items are mined by rule from held-out Korean
regulation and verified against the source, not written and reviewed by
engineers, so an absolute score is not comparable to a published leaderboard.
The delta on identical items is.

## Tracks / 트랙

| Track | Items | Types |
|---|---:|---|
{row('track1', 'track 1 — DAPT, perplexity')}
{row('track2', 'track 2 — SFT, regulation facts')}
{row('track3', 'track 3 — VLM, IFC elements')}

Held out: {totals.get('pdf_documents', 0)} of {totals.get('dataset_documents', 0)} documents
({totals.get('pdf_chunks', 0)} chunks), {totals.get('ifc_models', 0)} IFC models.

- **numeric** — a stipulated threshold. Graded by parsing the number and
  comparing with relative tolerance, not by searching the reply for digits.
- **nameset** — the entries of an enumerated list, graded as set P/R/F1 so a
  partial answer scores partially.
- **mapping** — IFC type to count, key F1 and value accuracy reported apart.

Cognitive levels follow AECBench's taxonomy; everything auto-keyable from this
corpus sits at memorization and understanding. Calculation and application need
exam papers or written rubrics and are out of scope for this version.

## Bilingual prompts / 이중 언어

Every item carries `question_ko` and `question_en`, and numeric items carry
`answer_ko` and `answer_en` with the unit in its English form. Korean is the
evaluation language: the regulation, its terminology and its users are Korean,
and translating a clause reference changes the question — the same reasoning
KMMLU used in collecting original Korean exams rather than translating an
English set. Subjects that are legal terms of art stay in Korean inside the
English frame rather than being paraphrased into something the source does not
say.

## Provenance and contamination / 출처와 오염

Every item records the generated file it was mined from, the row index inside
it, the character span inside that row, and a sha256 of the text. `provenance.jsonl`
carries that evidence per item and `verify_provenance.py` re-checks it:

| Check | Result |
|---|---|
| items checked | {cont.get('items', 0)} |
| fully verified | {cont.get('fully_verified', 0)} |
| failures | {cont.get('failures') or 'none'} |

The checks are `source_exists`, `source_matches` (the row still hashes to the
recorded digest), `in_holdout`, and `absent_from_train` — the last by digest
over every text field of the training split, not by document name. That
distinction is not academic: this corpus collects the same regulation more than
once, under names differing by a suffix and as amendment-plus-original pairs, so
excluding a held-out document by name still left 759 of its chunks in the
training data under a sibling document's name. `make_train_split.py` now drops
those rows as well.

## Usage / 사용법

```bash
python build_all.py -i ../ai_ready_full   # holdout, tracks, split, verify, export
python evaluate.py --model <base> --tag base
# fine-tune on data/train/, never on the source dataset directly
python evaluate.py --model <tuned> --tag tuned
python compare.py --base base --after tuned --markdown report.md
```

`lm_eval/` holds task files for lm-evaluation-harness. Its `exact_match` is
stricter than the grader here, which parses numbers with tolerance and compares
sets as sets; use `evaluate.py` for the reported number.

## Limitations / 한계

- Items are rule-mined, not expert-reviewed. Sufficient for a before/after
  delta, not for a public leaderboard without a review pass — the step both
  AECBench and KMMLU spent most of their effort on.
- Track 3 is bounded by the corpus: after parser regression fixtures are
  excluded, {totals.get('ifc_models', 0)} models remain held out, which is a directional signal
  rather than a ranking. Recording per-group membership in `ifc_processor.py`
  would lift it from whole-model renders to every render.
- Track 1 needs prompt-token logprobs. Ollama does not return them, so
  `evaluate.py` reports null there and the measurement needs vLLM or
  `llama-perplexity` against the same file.
- Numeric items inherit whatever ambiguity the source clause has. Overlapping
  subjects sharing a unit and qualifier are dropped rather than graded.

## Do not / 금지

Do not train on the items or on the held-out documents; use `data/train/`.
Do not change the holdout seed once a base checkpoint has been scored — a
different seed reserves different documents, and two runs on different items are
not comparable.

## Licensing / 라이선스

The items quote Korean public regulation and are keyed from IFC files in the
source corpus. Redistribution follows whatever terms attach to those sources;
this repository asserts no separate licence over the questions.
"""
    path = export_dir / "DATASET_CARD.md"
    path.write_text(body, encoding="utf-8")
    return path


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description="Package the benchmark for distribution",
        formatter_class=argparse.RawDescriptionHelpFormatter, epilog=__doc__)
    add_common_args(ap)
    ap.add_argument("--export-dir", metavar="DIR",
                    help="where packaging artefacts go (default <out-dir>/export)")
    ap.add_argument("--no-lm-eval", action="store_true", help="skip the harness task files")
    ap.add_argument("--no-card", action="store_true", help="skip the dataset card")
    args = ap.parse_args(argv)

    cfg = resolve_config(args)
    describe(cfg)

    export_dir = Path(args.export_dir) if args.export_dir else cfg["out_dir"] / "export"
    export_dir.mkdir(parents=True, exist_ok=True)

    LOG.info("wrote %s", write_manifest(cfg, export_dir))
    if not args.no_lm_eval and cfg.get("export", {}).get("lm_eval_harness", True):
        for p in write_lm_eval(cfg, export_dir):
            LOG.info("wrote %s", p)
    if not args.no_card and cfg.get("export", {}).get("dataset_card", True):
        LOG.info("wrote %s", write_card(cfg, export_dir))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
